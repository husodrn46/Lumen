-- Beta.2: sipariş ve paket kimliklerini ayırır; eski kayıtlar boş paket kimliğiyle korunur.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF COL_LENGTH('dbo.M_ET_SIPARIS','PAKET_KIMLIGI') IS NULL
    ALTER TABLE dbo.M_ET_SIPARIS ADD PAKET_KIMLIGI NVARCHAR(100) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_ET_PAKET DEFAULT N'' WITH VALUES;
IF COL_LENGTH('dbo.M_ET_SIPARIS','KAYNAK') IS NULL
    ALTER TABLE dbo.M_ET_SIPARIS ADD KAYNAK VARCHAR(20) NOT NULL CONSTRAINT DF_ET_KAYNAK DEFAULT 'lumen' WITH VALUES;
IF COL_LENGTH('dbo.M_ET_SIPARIS','KAYNAK_DURUMU') IS NULL
    ALTER TABLE dbo.M_ET_SIPARIS ADD KAYNAK_DURUMU NVARCHAR(50) NULL, KAYNAK_ENGELI NVARCHAR(500) NULL;
IF COL_LENGTH('dbo.M_ET_ICE_AKTARIM','BICIM') IS NULL
    ALTER TABLE dbo.M_ET_ICE_AKTARIM ADD BICIM VARCHAR(20) NOT NULL CONSTRAINT DF_ET_BICIM DEFAULT 'lumen' WITH VALUES;
-- Eski iki kolonlu kısıt yalnız paket kolonu hazır olduğunda değiştirilir.
IF EXISTS (SELECT 1 FROM sys.key_constraints K WHERE K.parent_object_id=OBJECT_ID('dbo.M_ET_SIPARIS')
    AND K.name='UQ_ET_SIPARIS_NUMARA' AND 2=(SELECT COUNT(*) FROM sys.index_columns I
        WHERE I.object_id=K.parent_object_id AND I.index_id=K.unique_index_id AND I.key_ordinal>0))
    ALTER TABLE dbo.M_ET_SIPARIS DROP CONSTRAINT UQ_ET_SIPARIS_NUMARA;
IF NOT EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID('dbo.M_ET_SIPARIS') AND name='UQ_ET_SIPARIS_NUMARA')
    ALTER TABLE dbo.M_ET_SIPARIS ADD CONSTRAINT UQ_ET_SIPARIS_NUMARA UNIQUE(KANAL_ID,HARICI_NO,PAKET_KIMLIGI);
COMMIT;
GO
