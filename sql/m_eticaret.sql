-- E-ticaret kutusu: iki modda ortak; ana veri kimlikleri moda göre doğrulanır.
IF COL_LENGTH('dbo.M_P_YETKI', 'M33') IS NULL
    ALTER TABLE dbo.M_P_YETKI ADD M33 INT NOT NULL CONSTRAINT DF_M_P_YETKI_M33 DEFAULT 0 WITH VALUES;
GO
IF OBJECT_ID('dbo.M_ET_KANAL', 'U') IS NULL
CREATE TABLE dbo.M_ET_KANAL (
 ID INT IDENTITY PRIMARY KEY, FIRMA INT NOT NULL, AD NVARCHAR(100) NOT NULL,
 TUR VARCHAR(20) NOT NULL, AKTIF BIT NOT NULL DEFAULT 1,
 CARI_ID INT NULL, DEPO_NO INT NULL, PERSONEL_ID INT NULL,
 OLUSTURAN INT NOT NULL, GUNCELLEYEN INT NOT NULL,
 OLUSTURMA DATETIME2 NOT NULL DEFAULT SYSDATETIME(), GUNCELLEME DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 SURUM ROWVERSION,
 CONSTRAINT CK_ET_KANAL_TUR CHECK (TUR IN ('trendyol','hepsiburada','woocommerce','shopify','site','diger'))
);
GO
IF OBJECT_ID('dbo.M_ET_ICE_AKTARIM', 'U') IS NULL
CREATE TABLE dbo.M_ET_ICE_AKTARIM (
 ID INT IDENTITY PRIMARY KEY, KANAL_ID INT NOT NULL REFERENCES dbo.M_ET_KANAL(ID),
 DOSYA_ADI NVARCHAR(200) NOT NULL, TUR VARCHAR(4) NOT NULL, OZET CHAR(64) NOT NULL,
 HAM NVARCHAR(MAX) NOT NULL, SONUC NVARCHAR(MAX) NULL,
 KULLANICI INT NOT NULL, ALINMA DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);
GO
IF OBJECT_ID('dbo.M_ET_SIPARIS', 'U') IS NULL
CREATE TABLE dbo.M_ET_SIPARIS (
 ID INT IDENTITY PRIMARY KEY, KANAL_ID INT NOT NULL REFERENCES dbo.M_ET_KANAL(ID),
 AKTARIM_ID INT NOT NULL REFERENCES dbo.M_ET_ICE_AKTARIM(ID),
 HARICI_ID NVARCHAR(150) COLLATE Latin1_General_100_BIN2 NOT NULL,
 HARICI_NO NVARCHAR(150) COLLATE Latin1_General_100_BIN2 NOT NULL,
 DURUM VARCHAR(20) NOT NULL DEFAULT 'yeni',
 HAM NVARCHAR(MAX) NOT NULL, NORMAL NVARCHAR(MAX) NOT NULL,
 CARI_ID INT NULL, DEPO_NO INT NULL, PERSONEL_ID INT NULL,
 ONAY_GOVDE NVARCHAR(MAX) NULL, ONAY_OZET CHAR(64) NULL,
 ANAHTAR CHAR(64) NOT NULL, HEDEF_MOD VARCHAR(10) NULL, HEDEF_DONEM NVARCHAR(30) NULL,
 FIS_ID INT NULL, FIS_NO NVARCHAR(30) NULL,
 DENEME INT NOT NULL DEFAULT 0, SON_HATA NVARCHAR(500) NULL,
 ALINMA DATETIME2 NOT NULL DEFAULT SYSDATETIME(), AKTARILMA DATETIME2 NULL,
 OLUSTURAN INT NOT NULL, AKTARAN INT NULL, SURUM ROWVERSION,
 CONSTRAINT UQ_ET_SIPARIS_KIMLIK UNIQUE (KANAL_ID,HARICI_ID),
 CONSTRAINT UQ_ET_SIPARIS_NUMARA UNIQUE (KANAL_ID,HARICI_NO),
 CONSTRAINT CK_ET_SIPARIS_DURUM CHECK (DURUM IN ('yeni','esleme','hazir','aktarildi','iptal','hatali')),
 CONSTRAINT CK_ET_SIPARIS_HEDEF CHECK (DURUM <> 'aktarildi' OR (FIS_ID IS NOT NULL AND FIS_NO IS NOT NULL AND AKTARILMA IS NOT NULL))
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.M_ET_SIPARIS') AND name='IX_ET_SIPARIS_KUTU')
CREATE INDEX IX_ET_SIPARIS_KUTU ON dbo.M_ET_SIPARIS (KANAL_ID,DURUM,ID);
GO
IF OBJECT_ID('dbo.M_ET_SIPARIS_SATIR', 'U') IS NULL
CREATE TABLE dbo.M_ET_SIPARIS_SATIR (
 ID INT IDENTITY PRIMARY KEY, SIPARIS_ID INT NOT NULL REFERENCES dbo.M_ET_SIPARIS(ID), SIRA INT NOT NULL,
 SKU NVARCHAR(150) COLLATE Latin1_General_100_BIN2 NULL,
 BARKOD NVARCHAR(150) COLLATE Latin1_General_100_BIN2 NULL,
 AD NVARCHAR(200) NOT NULL, BIRIM NVARCHAR(30) NOT NULL,
 MIKTAR DECIMAL(19,6) NOT NULL, FIYAT DECIMAL(19,6) NOT NULL, KDV DECIMAL(5,2) NOT NULL,
 KDV_DAHIL BIT NOT NULL, STOK_ID INT NULL,
 CONSTRAINT UQ_ET_SATIR UNIQUE(SIPARIS_ID,SIRA)
);
GO
IF OBJECT_ID('dbo.M_ET_URUN_ESLEME', 'U') IS NULL
CREATE TABLE dbo.M_ET_URUN_ESLEME (
 ID INT IDENTITY PRIMARY KEY, KANAL_ID INT NOT NULL REFERENCES dbo.M_ET_KANAL(ID),
 TUR VARCHAR(6) NOT NULL, DEGER NVARCHAR(150) COLLATE Latin1_General_100_BIN2 NOT NULL,
 STOK_ID INT NOT NULL, BIRIM NVARCHAR(30) NOT NULL, CARPAN DECIMAL(19,6) NOT NULL,
 KULLANICI INT NOT NULL, GUNCELLEME DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT UQ_ET_ESLEME UNIQUE(KANAL_ID,TUR,DEGER),
 CONSTRAINT CK_ET_ESLEME_TUR CHECK(TUR IN ('sku','barkod')),
 CONSTRAINT CK_ET_ESLEME_CARPAN CHECK(CARPAN >= 1)
);
GO
IF OBJECT_ID('dbo.M_ET_OLAY', 'U') IS NULL
CREATE TABLE dbo.M_ET_OLAY (
