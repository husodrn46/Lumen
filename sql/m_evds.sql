IF COL_LENGTH('dbo.M_P_YETKI','M34') IS NULL
    ALTER TABLE dbo.M_P_YETKI ADD M34 INT NOT NULL CONSTRAINT DF_M_P_YETKI_M34 DEFAULT 0 WITH VALUES;
GO
IF OBJECT_ID('dbo.M_EVDS_BAGLANTI','U') IS NULL
CREATE TABLE dbo.M_EVDS_BAGLANTI (
 FIRMA INT NOT NULL, KULLANICI INT NOT NULL, SIFRELI_ANAHTAR VARCHAR(1024) NOT NULL,
 GUNCELLEME DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT PK_EVDS_BAGLANTI PRIMARY KEY (FIRMA,KULLANICI)
);
GO
IF OBJECT_ID('dbo.M_EVDS_ONBELLEK','U') IS NULL
CREATE TABLE dbo.M_EVDS_ONBELLEK (
 FIRMA INT NOT NULL, KULLANICI INT NOT NULL, OZET CHAR(64) NOT NULL,
 VERI NVARCHAR(MAX) NULL, ALINMA DATETIME2 NULL,
 SON_DENEME DATETIME2 NOT NULL DEFAULT SYSDATETIME(), HATA NVARCHAR(500) NULL,
 CONSTRAINT PK_EVDS_ONBELLEK PRIMARY KEY (FIRMA,KULLANICI,OZET)
);
GO
