-- Kanal bağlantısı ve kaldığı yerden sürdürülebilen salt okunur sipariş alımı.
IF OBJECT_ID('dbo.M_ET_BAGLANTI','U') IS NULL
CREATE TABLE dbo.M_ET_BAGLANTI (
 KANAL_ID INT NOT NULL PRIMARY KEY REFERENCES dbo.M_ET_KANAL(ID),
 ORTAM VARCHAR(5) NOT NULL, SATICI_ID VARCHAR(40) NOT NULL,
 TUR VARCHAR(20) NOT NULL DEFAULT 'trendyol', ISTEMCI VARCHAR(100) NULL,
 SIFRELI VARCHAR(2048) NOT NULL, SURUM CHAR(32) NOT NULL,
 SON_ISTEK DATETIME2 NULL, GUNCELLEYEN INT NOT NULL,
 GUNCELLEME DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
 CONSTRAINT CK_ET_BAGLANTI_ORTAM CHECK (ORTAM IN ('stage','prod'))
);
GO
-- Eski Trendyol bağlantılarının şifreli verisi ve sürümü aynı kalır.
IF COL_LENGTH('dbo.M_ET_BAGLANTI','SATICI_ID')<40
    ALTER TABLE dbo.M_ET_BAGLANTI ALTER COLUMN SATICI_ID VARCHAR(40) NOT NULL;
IF COL_LENGTH('dbo.M_ET_BAGLANTI','TUR') IS NULL
    ALTER TABLE dbo.M_ET_BAGLANTI ADD TUR VARCHAR(20) NOT NULL CONSTRAINT DF_ET_BAGLANTI_TUR DEFAULT 'trendyol' WITH VALUES;
IF COL_LENGTH('dbo.M_ET_BAGLANTI','ISTEMCI') IS NULL
    ALTER TABLE dbo.M_ET_BAGLANTI ADD ISTEMCI VARCHAR(100) NULL;
GO
IF OBJECT_ID('dbo.M_ET_CEKIM','U') IS NULL
CREATE TABLE dbo.M_ET_CEKIM (
 ID INT IDENTITY PRIMARY KEY, KANAL_ID INT NOT NULL REFERENCES dbo.M_ET_KANAL(ID),
 BAG_SURUM CHAR(32) NOT NULL, FILTRE NVARCHAR(1000) NOT NULL,
 IMLEC NVARCHAR(4000) NULL, DURUM VARCHAR(12) NOT NULL DEFAULT 'suruyor',
 SAYFA INT NOT NULL DEFAULT 0, YENI INT NOT NULL DEFAULT 0, MUKERRER INT NOT NULL DEFAULT 0,
 CAKISMA INT NOT NULL DEFAULT 0, HATALI INT NOT NULL DEFAULT 0, ESKI INT NOT NULL DEFAULT 0,
 DENEME INT NOT NULL DEFAULT 0, HATA NVARCHAR(500) NULL, SONRAKI DATETIME2 NULL,
 KILIT CHAR(32) NULL, KILIT_BITIS DATETIME2 NULL,
 KULLANICI INT NOT NULL, SON_KULLANICI INT NOT NULL,
 BASLANGIC DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), BITIS DATETIME2 NULL,
 CONSTRAINT CK_ET_CEKIM_DURUM CHECK (DURUM IN ('suruyor','tamam','durduruldu'))
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.M_ET_CEKIM') AND name='UQ_ET_CEKIM_AKTIF')
CREATE UNIQUE INDEX UQ_ET_CEKIM_AKTIF ON dbo.M_ET_CEKIM(KANAL_ID) WHERE DURUM='suruyor';
GO
IF OBJECT_ID('dbo.M_ET_CEKIM_SAYFA','U') IS NULL
CREATE TABLE dbo.M_ET_CEKIM_SAYFA (
 ID INT IDENTITY PRIMARY KEY, CEKIM_ID INT NOT NULL REFERENCES dbo.M_ET_CEKIM(ID),
 SIRA INT NOT NULL, ISTEK_OZET CHAR(64) NOT NULL,
 AKTARIM_ID INT NOT NULL REFERENCES dbo.M_ET_ICE_AKTARIM(ID),
 ALINMA DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), VERI_OZET CHAR(64) NULL,
 CONSTRAINT UQ_ET_CEKIM_SAYFA UNIQUE (CEKIM_ID,SIRA),
 CONSTRAINT UQ_ET_CEKIM_IMLEC UNIQUE (CEKIM_ID,ISTEK_OZET)
);
GO
IF COL_LENGTH('dbo.M_ET_CEKIM_SAYFA','VERI_OZET') IS NULL
    ALTER TABLE dbo.M_ET_CEKIM_SAYFA ADD VERI_OZET CHAR(64) NULL;
GO
