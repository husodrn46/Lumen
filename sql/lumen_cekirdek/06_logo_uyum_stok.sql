-- Lumen çekirdek — 06: stok ana verisi için LOGO uyumlu görünümler (geçiş adaptörü)
--
-- Bağımsız modda tablo öneki 'dbo.LMV_' olur; stok kartını LOGO kolon adlarıyla
-- okuyan sorgular ({$firma}ITEMS, {$firma}ITMUNITA, {$firma}UNITBARCODE,
-- {$firma}PRCLIST, {$firmadonemx}STINVTOT) kod değişmeden LM_ tablolarını okur.
-- Stok ana verisine yazan az sayıdaki ekran (ürün adı, koli ölçüsü, barkod,
-- fiyat) INSTEAD OF tetikleyicileriyle LM_ tablolarına yazar.
--
-- Birim modeli: LOGO'da her stok bir birim setine (UNITSETL) bağlıdır. Burada her
-- stok kendi setidir: UNITSETREF = LM_STOK.ID, set satırları = LM_STOK_BIRIM
-- (LOGICALREF = LM_STOK_BIRIM.ID, LINENR 1 = ana birim, diğerleri birim tanım sırasıyla:
-- ADET, KOLI, PAKET — LOGO demosundaki gibi 2. satır koli). ITMUNITA da aynı satırlardır.
-- Fiyat türü: LOGO PTYPE 1 alış, 2 satış ↔ LM_FIYAT.TUR 2 alış, 1 satış.
-- Ambar: INVENNO = LM_DEPO.NO; -1 = tüm ambarlar toplamı.
-- ============================================================================

-- Stok birimlerinin set içi sırası (ana birim 1).
CREATE OR ALTER VIEW dbo.LMV_STOK_BIRIM_SIRA AS
SELECT SB.ID, SB.STOK_ID, SB.BIRIM_ID, SB.CARPAN, SB.AGIRLIK_KG, SB.UZUNLUK_MM, SB.GENISLIK_MM, SB.YUKSEKLIK_MM,
       CAST(ROW_NUMBER() OVER (PARTITION BY SB.STOK_ID
            ORDER BY CASE WHEN SB.BIRIM_ID = S.ANA_BIRIM_ID THEN 0 ELSE 1 END, SB.BIRIM_ID) AS SMALLINT) AS LINENR,
       CAST(CASE WHEN SB.BIRIM_ID = S.ANA_BIRIM_ID THEN 1 ELSE 0 END AS SMALLINT) AS MAINUNIT
FROM dbo.LM_STOK_BIRIM SB
JOIN dbo.LM_STOK S ON S.ID = SB.STOK_ID;
GO

CREATE OR ALTER VIEW dbo.LMV_ITEMS AS
SELECT S.ID AS LOGICALREF, S.KOD AS CODE, S.AD AS NAME, CAST(NULL AS NVARCHAR(200)) AS NAME2, CAST(NULL AS NVARCHAR(200)) AS NAME3,
       CAST(CASE WHEN S.STOK_TAKIPLI = 1 THEN 1 ELSE 4 END AS SMALLINT) AS CARDTYPE,   -- 1 ticari mal, 4 hizmet
       CAST(0 AS SMALLINT) AS CLASSTYPE,
       CASE WHEN S.AKTIF = 1 THEN 0 ELSE 1 END AS ACTIVE,
       S.ID AS UNITSETREF, S.GRUP AS STGRPCODE, S.OZEL_KOD AS SPECODE,
       CAST(NULL AS NVARCHAR(40)) AS SPECODE2, CAST(NULL AS NVARCHAR(40)) AS SPECODE3, CAST(NULL AS NVARCHAR(40)) AS CYPHCODE,
       CAST(NULL AS NVARCHAR(40)) AS PRODUCERCODE,
       S.KDV_ORANI AS VAT, S.KDV_ORANI AS SELLVAT, S.KDV_ORANI AS RETURNVAT
FROM dbo.LM_STOK S;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_ITEMS_GUNCELLE ON dbo.LMV_ITEMS INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    UPDATE S SET
        KOD = I.CODE, AD = I.NAME, GRUP = I.STGRPCODE, OZEL_KOD = I.SPECODE,
        KDV_ORANI = COALESCE(I.SELLVAT, I.VAT, S.KDV_ORANI),
        AKTIF = CASE WHEN I.ACTIVE = 0 THEN 1 ELSE 0 END,
        GUNCELLEME = SYSDATETIME()
    FROM dbo.LM_STOK S JOIN inserted I ON I.LOGICALREF = S.ID;
END;
GO

CREATE OR ALTER VIEW dbo.LMV_UNITSETL AS
SELECT R.ID AS LOGICALREF, B.KOD AS CODE, B.AD AS NAME, R.STOK_ID AS UNITSETREF, R.LINENR, R.MAINUNIT,
       CAST(1 AS FLOAT) AS CONVFACT1, CAST(R.CARPAN AS FLOAT) AS CONVFACT2
FROM dbo.LMV_STOK_BIRIM_SIRA R
JOIN dbo.LM_BIRIM B ON B.ID = R.BIRIM_ID;
GO

CREATE OR ALTER VIEW dbo.LMV_ITMUNITA AS
SELECT R.ID AS LOGICALREF, R.STOK_ID AS ITEMREF, R.LINENR, R.ID AS UNITLINEREF,
       CAST(1 AS FLOAT) AS CONVFACT1, CAST(R.CARPAN AS FLOAT) AS CONVFACT2,
       CAST(R.AGIRLIK_KG AS FLOAT) AS WEIGHT, CAST(R.UZUNLUK_MM AS FLOAT) AS LENGTH,
       CAST(R.GENISLIK_MM AS FLOAT) AS WIDTH, CAST(R.YUKSEKLIK_MM AS FLOAT) AS HEIGHT,
       CAST(CASE WHEN R.AGIRLIK_KG > 0 THEN 18 ELSE 0 END AS INT) AS WEIGHTREF,
       CAST(CASE WHEN R.UZUNLUK_MM > 0 THEN 2 ELSE 0 END AS INT) AS LENGTHREF,
       CAST(CASE WHEN R.GENISLIK_MM > 0 THEN 2 ELSE 0 END AS INT) AS WIDTHREF,
       CAST(CASE WHEN R.YUKSEKLIK_MM > 0 THEN 2 ELSE 0 END AS INT) AS HEIGHTREF,
       CAST(1 AS SMALLINT) AS MTRLCLAS, CAST(1 AS SMALLINT) AS PURCHCLAS, CAST(1 AS SMALLINT) AS SALESCLAS,
       CAST(1 AS SMALLINT) AS RECSTATUS
FROM dbo.LMV_STOK_BIRIM_SIRA R;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_ITMUNITA_GUNCELLE ON dbo.LMV_ITMUNITA INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    UPDATE SB SET
        CARPAN = CASE WHEN I.CONVFACT2 > 0 THEN CAST(I.CONVFACT2 / NULLIF(I.CONVFACT1, 0) AS DECIMAL(19,6)) ELSE SB.CARPAN END,
        AGIRLIK_KG = I.WEIGHT, UZUNLUK_MM = I.LENGTH, GENISLIK_MM = I.WIDTH, YUKSEKLIK_MM = I.HEIGHT
    FROM dbo.LM_STOK_BIRIM SB JOIN inserted I ON I.LOGICALREF = SB.ID;
END;
GO

-- Bağımsız modda her stok-birim çiftinin satırı zaten vardır: ekleme o satırın güncellemesidir
-- (UNITLINEREF = LM_STOK_BIRIM.ID).
CREATE OR ALTER TRIGGER dbo.TR_LMV_ITMUNITA_EKLE ON dbo.LMV_ITMUNITA INSTEAD OF INSERT AS
BEGIN
    SET NOCOUNT ON;
    UPDATE SB SET
        AGIRLIK_KG = I.WEIGHT, UZUNLUK_MM = I.LENGTH, GENISLIK_MM = I.WIDTH, YUKSEKLIK_MM = I.HEIGHT
    FROM dbo.LM_STOK_BIRIM SB JOIN inserted I ON I.UNITLINEREF = SB.ID AND I.ITEMREF = SB.STOK_ID;
END;
GO

CREATE OR ALTER VIEW dbo.LMV_UNITBARCODE AS
SELECT BK.ID AS LOGICALREF, BK.STOK_ID AS ITEMREF, SB.ID AS ITMUNITAREF, SB.ID AS UNITLINEREF,
       CAST(1 AS SMALLINT) AS LINENR, BK.BARKOD AS BARCODE, CAST(0 AS SMALLINT) AS TYP,
       CAST(0 AS INT) AS VARIANTREF, CAST(0 AS INT) AS ORGLOGICREF, CAST(1 AS SMALLINT) AS RECSTATUS,
       CAST(0 AS SMALLINT) AS SITEID, CAST(0 AS SMALLINT) AS WBARCODESHIFT
FROM dbo.LM_BARKOD BK
LEFT JOIN dbo.LM_STOK_BIRIM SB ON SB.STOK_ID = BK.STOK_ID AND SB.BIRIM_ID = BK.BIRIM_ID;
GO

-- Barkodun birimi: UNITLINEREF/ITMUNITAREF (LM_STOK_BIRIM.ID) verilmişse o, yoksa stokun ana birimi.
CREATE OR ALTER TRIGGER dbo.TR_LMV_UNITBARCODE_EKLE ON dbo.LMV_UNITBARCODE INSTEAD OF INSERT AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO dbo.LM_BARKOD (STOK_ID, BIRIM_ID, BARKOD)
    SELECT I.ITEMREF, COALESCE(SB.BIRIM_ID, S.ANA_BIRIM_ID), I.BARCODE
    FROM inserted I
    JOIN dbo.LM_STOK S ON S.ID = I.ITEMREF
    LEFT JOIN dbo.LM_STOK_BIRIM SB ON SB.STOK_ID = I.ITEMREF
         AND SB.ID = COALESCE(NULLIF(I.UNITLINEREF, 0), NULLIF(I.ITMUNITAREF, 0));
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_UNITBARCODE_GUNCELLE ON dbo.LMV_UNITBARCODE INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    UPDATE BK SET
        BARKOD = I.BARCODE,
        BIRIM_ID = COALESCE((SELECT SB.BIRIM_ID FROM dbo.LM_STOK_BIRIM SB
                              WHERE SB.STOK_ID = BK.STOK_ID AND SB.ID = COALESCE(NULLIF(I.UNITLINEREF, 0), NULLIF(I.ITMUNITAREF, 0))), BK.BIRIM_ID)
    FROM dbo.LM_BARKOD BK JOIN inserted I ON I.LOGICALREF = BK.ID;
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_UNITBARCODE_SIL ON dbo.LMV_UNITBARCODE INSTEAD OF DELETE AS
BEGIN
    SET NOCOUNT ON;
    DELETE BK FROM dbo.LM_BARKOD BK JOIN deleted D ON D.LOGICALREF = BK.ID;
END;
GO

CREATE OR ALTER VIEW dbo.LMV_PRCLIST AS
SELECT F.ID AS LOGICALREF, F.STOK_ID AS CARDREF, CAST(3 - F.TUR AS SMALLINT) AS PTYPE, CAST(F.FIYAT AS FLOAT) AS PRICE,
       SB.ID AS UOMREF, CAST(F.KDV_DAHIL AS SMALLINT) AS INCVAT,
       CAST(CASE F.PARA_BIRIMI WHEN 'USD' THEN 1 WHEN 'EUR' THEN 20 WHEN 'GBP' THEN 17 ELSE 0 END AS SMALLINT) AS CURRENCY,
       CAST(0 AS SMALLINT) AS ACTIVE, CAST(F.BASLANGIC AS DATETIME) AS BEGDATE, CAST(NULL AS DATETIME) AS ENDDATE,
       CAST(0 AS INT) AS PAYPLANREF, CAST(0 AS SMALLINT) AS PRIORITY, CAST(0 AS SMALLINT) AS MTRLTYPE,
       CAST(NULL AS NVARCHAR(40)) AS CLIENTCODE, CAST(NULL AS NVARCHAR(40)) AS CLSPECODE, CAST(NULL AS NVARCHAR(40)) AS CODE,
       CAST(NULL AS NVARCHAR(200)) AS DEFINITION_, CAST(NULL AS NVARCHAR(40)) AS GRPCODE,
       CAST(0 AS SMALLINT) AS LEADTIME, CAST(NULL AS NVARCHAR(200)) AS CONDITION, CAST(0 AS SMALLINT) AS SHIPTYP,
       CAST(0 AS SMALLINT) AS SPECIALIZED, CAST(0 AS INT) AS CAPIBLOCK_CREATEDBY, CAST(NULL AS DATETIME) AS CAPIBLOCK_CREADEDDATE,
       CAST(0 AS SMALLINT) AS CAPIBLOCK_CREATEDHOUR, CAST(0 AS SMALLINT) AS CAPIBLOCK_CREATEDMIN, CAST(0 AS SMALLINT) AS CAPIBLOCK_CREATEDSEC,
       CAST(0 AS INT) AS CAPIBLOCK_MODIFIEDBY, CAST(0 AS SMALLINT) AS CAPIBLOCK_MODIFIEDHOUR, CAST(0 AS SMALLINT) AS CAPIBLOCK_MODIFIEDMIN,
       CAST(0 AS SMALLINT) AS CAPIBLOCK_MODIFIEDSEC, CAST(0 AS SMALLINT) AS SITEID, CAST(1 AS SMALLINT) AS RECSTATUS,
       CAST(0 AS INT) AS ORGLOGICREF, CAST(0 AS INT) AS WFSTATUS, CAST(0 AS SMALLINT) AS UNITCONVERT, CAST(0 AS INT) AS EXTACCESSFLAGS,
       CAST(NULL AS NVARCHAR(40)) AS CYPHCODE, CAST(NULL AS NVARCHAR(40)) AS ORGLOGOID, CAST(NULL AS NVARCHAR(40)) AS TRADINGGRP,
       CAST(0 AS INT) AS BEGTIME, CAST(0 AS INT) AS ENDTIME, CAST(0 AS INT) AS ORDERNR, CAST(0 AS SMALLINT) AS GENIUSPAYTYPE,
       CAST(NULL AS NVARCHAR(40)) AS GENIUSSHPNR, CAST(0 AS SMALLINT) AS PRCALTERTYP1, CAST(0 AS FLOAT) AS PRCALTERLMT1,
       CAST(0 AS SMALLINT) AS PRCALTERTYP2, CAST(0 AS FLOAT) AS PRCALTERLMT2, CAST(0 AS SMALLINT) AS PRCALTERTYP3,
       CAST(0 AS FLOAT) AS PRCALTERLMT3, CAST(0 AS INT) AS PURCHCONTREF, CAST(0 AS SMALLINT) AS BRANCH, CAST(0 AS FLOAT) AS COSTVAL,
       CAST(NULL AS NVARCHAR(40)) AS CLTRADINGGRP, CAST(NULL AS NVARCHAR(40)) AS CLCYPHCODE, CAST(NULL AS NVARCHAR(40)) AS CLSPECODE2,
       CAST(NULL AS NVARCHAR(40)) AS CLSPECODE3, CAST(NULL AS NVARCHAR(40)) AS CLSPECODE4, CAST(NULL AS NVARCHAR(40)) AS CLSPECODE5
FROM dbo.LM_FIYAT F
LEFT JOIN dbo.LM_STOK_BIRIM SB ON SB.STOK_ID = F.STOK_ID AND SB.BIRIM_ID = F.BIRIM_ID;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_PRCLIST_GUNCELLE ON dbo.LMV_PRCLIST INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    UPDATE F SET FIYAT = CAST(I.PRICE AS DECIMAL(19,4))
    FROM dbo.LM_FIYAT F JOIN inserted I ON I.LOGICALREF = F.ID;
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_PRCLIST_EKLE ON dbo.LMV_PRCLIST INSTEAD OF INSERT AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO dbo.LM_FIYAT (STOK_ID, TUR, BIRIM_ID, FIYAT, PARA_BIRIMI, KDV_DAHIL, BASLANGIC)
    SELECT I.CARDREF, CASE WHEN I.PTYPE = 1 THEN 2 ELSE 1 END,
           COALESCE(SB.BIRIM_ID, S.ANA_BIRIM_ID), CAST(I.PRICE AS DECIMAL(19,4)),
           CASE I.CURRENCY WHEN 1 THEN 'USD' WHEN 20 THEN 'EUR' WHEN 17 THEN 'GBP' ELSE 'TRY' END,
           CASE WHEN I.INCVAT = 1 THEN 1 ELSE 0 END, CAST(COALESCE(I.BEGDATE, SYSDATETIME()) AS DATE)
    FROM inserted I
    JOIN dbo.LM_STOK S ON S.ID = I.CARDREF
    LEFT JOIN dbo.LM_STOK_BIRIM SB ON SB.STOK_ID = I.CARDREF AND SB.ID = I.UOMREF;
END;
GO

-- Eldeki stok (LOGO: LV_..._STINVTOT). INVENNO -1 = tüm ambarlar toplamı.
CREATE OR ALTER VIEW dbo.LMV_STINVTOT AS
SELECT CAST(NULL AS INT) AS LOGICALREF, M.STOK_ID AS STOCKREF, CAST(D.NO AS SMALLINT) AS INVENNO,
       CAST(M.MIKTAR AS FLOAT) AS ONHAND, CAST(NULL AS DATETIME) AS DATE_
FROM dbo.LMV_STOK_MIKTAR M JOIN dbo.LM_DEPO D ON D.ID = M.DEPO_ID
UNION ALL
SELECT NULL, STOK_ID, CAST(-1 AS SMALLINT), CAST(SUM(MIKTAR) AS FLOAT), NULL
FROM dbo.LMV_STOK_MIKTAR GROUP BY STOK_ID;
GO

-- Ambarlar (LOGO: L_CAPIWHOUSE; sabit adlı sistem tablosu — lumen_tablo('depo') ile kullanılır).
CREATE OR ALTER VIEW dbo.LMV_CAPIWHOUSE AS
SELECT CAST(D.NO AS SMALLINT) AS NR, D.AD AS NAME,
       CAST(ISNULL((SELECT TRY_CAST(DEGER AS INT) FROM dbo.LM_AYAR WHERE ANAHTAR = 'firma_no'), 1) AS SMALLINT) AS FIRMNR
FROM dbo.LM_DEPO D WHERE D.AKTIF = 1;
GO
