-- ============================================================================
-- Lumen çekirdek şeması — 03: belgeler ve stok hareketleri
-- LOGO karşılıkları: ORFICHE/ORFLINE (sipariş), STFICHE/STLINE (irsaliye, üretim,
-- stok fişi), INVOICE (fatura). Lumen'de hepsi tek LM_BELGE tablosunun türleridir;
-- zincir KAYNAK_BELGE_ID ile izlenir (sipariş → irsaliye → fatura).
--
-- TUR:  1 sipariş, 2 irsaliye, 3 fatura, 4 iade faturası, 5 üretim fişi, 6 sayım/stok fişi
-- YON:  1 satış/çıkış, 2 alış/giriş
-- DURUM: 0 taslak, 1 onaylı, 9 iptal
--
-- Stok ve cari etkisi BELGE onaylanınca yazılır (LM_STOK_HAREKET / LM_CARI_HAREKET);
-- sipariş stok ve cariyi etkilemez, yalnız sevk/fatura miktarı izlenir.
-- ============================================================================

IF OBJECT_ID('dbo.LM_BELGE', 'U') IS NULL
CREATE TABLE dbo.LM_BELGE (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TUR TINYINT NOT NULL,
    YON TINYINT NOT NULL,
    NO NVARCHAR(30) NOT NULL,
    TARIH DATE NOT NULL,
    SAAT TIME(0) NOT NULL CONSTRAINT DF_LM_BELGE_SAAT DEFAULT CAST(SYSDATETIME() AS TIME(0)),
    VADE DATE NULL,
    CARI_ID INT NULL CONSTRAINT FK_LM_BELGE_CARI REFERENCES dbo.LM_CARI(ID),
    DEPO_ID INT NULL CONSTRAINT FK_LM_BELGE_DEPO REFERENCES dbo.LM_DEPO(ID),
    PERSONEL_ID INT NULL CONSTRAINT FK_LM_BELGE_PER REFERENCES dbo.LM_PERSONEL(ID),
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_BELGE_PB DEFAULT 'TRY' CONSTRAINT FK_LM_BELGE_PB REFERENCES dbo.LM_PARA_BIRIMI(KOD),
    KUR DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_BELGE_KUR DEFAULT 1,
    BRUT DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_BELGE_BRUT DEFAULT 0,      -- iskontosuz, KDV'siz
    ISKONTO DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_BELGE_ISK DEFAULT 0,
    KDV DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_BELGE_KDV DEFAULT 0,
    NET DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_BELGE_NET DEFAULT 0,        -- ödenecek (KDV dahil), TL
    DOVIZ_NET DECIMAL(19,4) NULL,                                           -- NET / KUR (dövizli belgede)
    GENEL_ISKONTO_ORANI DECIMAL(9,4) NULL,
    ACIKLAMA NVARCHAR(500) NULL,
    DURUM TINYINT NOT NULL CONSTRAINT DF_LM_BELGE_DURUM DEFAULT 0,
    KAYNAK_BELGE_ID INT NULL CONSTRAINT FK_LM_BELGE_KAYNAK REFERENCES dbo.LM_BELGE(ID),
    YAZDIRMA_SAYISI INT NOT NULL CONSTRAINT DF_LM_BELGE_YAZ DEFAULT 0,
    OLUSTURAN_ID INT NULL,
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_BELGE_OLU DEFAULT SYSDATETIME(),
    GUNCELLEYEN_ID INT NULL,
    GUNCELLEME DATETIME2(0) NULL,
    SURUM ROWVERSION,
    CONSTRAINT UQ_LM_BELGE_NO UNIQUE (TUR, YON, NO),
    CONSTRAINT CK_LM_BELGE_TUR CHECK (TUR BETWEEN 1 AND 6),
    CONSTRAINT CK_LM_BELGE_YON CHECK (YON IN (1, 2)),
    CONSTRAINT CK_LM_BELGE_DURUM CHECK (DURUM IN (0, 1, 9)),
    CONSTRAINT CK_LM_BELGE_KUR CHECK (KUR > 0)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_BELGE_CARI')
    CREATE INDEX IX_LM_BELGE_CARI ON dbo.LM_BELGE (CARI_ID, TARIH);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_BELGE_TUR_TARIH')
    CREATE INDEX IX_LM_BELGE_TUR_TARIH ON dbo.LM_BELGE (TUR, YON, TARIH);
GO

IF OBJECT_ID('dbo.LM_BELGE_SATIR', 'U') IS NULL
CREATE TABLE dbo.LM_BELGE_SATIR (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    BELGE_ID INT NOT NULL CONSTRAINT FK_LM_BS_BELGE REFERENCES dbo.LM_BELGE(ID) ON DELETE CASCADE,
    SIRA SMALLINT NOT NULL,
    STOK_ID INT NOT NULL CONSTRAINT FK_LM_BS_STOK REFERENCES dbo.LM_STOK(ID),
    BIRIM_ID INT NOT NULL CONSTRAINT FK_LM_BS_BIRIM REFERENCES dbo.LM_BIRIM(ID),
    CARPAN DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_BS_CARPAN DEFAULT 1,     -- satır birimi → ana birim
    MIKTAR DECIMAL(19,6) NOT NULL,                                          -- satır biriminde
    FIYAT DECIMAL(19,6) NOT NULL,                                           -- birim fiyat (belge para biriminde, KDV hariç)
    ISKONTO1 DECIMAL(9,4) NOT NULL CONSTRAINT DF_LM_BS_I1 DEFAULT 0,         -- %
    ISKONTO2 DECIMAL(9,4) NOT NULL CONSTRAINT DF_LM_BS_I2 DEFAULT 0,
    ISKONTO3 DECIMAL(9,4) NOT NULL CONSTRAINT DF_LM_BS_I3 DEFAULT 0,
    TUTAR DECIMAL(19,4) NOT NULL,                                           -- MIKTAR × FIYAT
    ISKONTO_TUTAR DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_BS_IT DEFAULT 0,   -- satır + dağıtılmış genel iskonto
    KDV_ORANI DECIMAL(5,2) NOT NULL,
    KDV_TUTAR DECIMAL(19,4) NOT NULL,
    NET DECIMAL(19,4) NOT NULL,                                             -- TUTAR - ISKONTO_TUTAR (KDV hariç)
    TESLIM_MIKTAR DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_BS_TES DEFAULT 0,  -- siparişte: sevk/fatura edilen
    KAYNAK_SATIR_ID INT NULL CONSTRAINT FK_LM_BS_KAYNAK REFERENCES dbo.LM_BELGE_SATIR(ID),
    ACIKLAMA NVARCHAR(250) NULL,
    SURUM ROWVERSION,
    CONSTRAINT CK_LM_BS_MIKTAR CHECK (MIKTAR >= 0)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_BS_BELGE')
    CREATE INDEX IX_LM_BS_BELGE ON dbo.LM_BELGE_SATIR (BELGE_ID, SIRA);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_BS_STOK')
    CREATE INDEX IX_LM_BS_STOK ON dbo.LM_BELGE_SATIR (STOK_ID);
GO

-- Stok hareketi: miktarlar ANA BİRİMDE. Mevcut stok = SUM(GIRIS) - SUM(CIKIS).
IF OBJECT_ID('dbo.LM_STOK_HAREKET', 'U') IS NULL
CREATE TABLE dbo.LM_STOK_HAREKET (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    STOK_ID INT NOT NULL CONSTRAINT FK_LM_SH_STOK REFERENCES dbo.LM_STOK(ID),
    DEPO_ID INT NOT NULL CONSTRAINT FK_LM_SH_DEPO REFERENCES dbo.LM_DEPO(ID),
    TARIH DATE NOT NULL,
    BELGE_ID INT NOT NULL CONSTRAINT FK_LM_SH_BELGE REFERENCES dbo.LM_BELGE(ID),
    SATIR_ID INT NULL CONSTRAINT FK_LM_SH_SATIR REFERENCES dbo.LM_BELGE_SATIR(ID),
    GIRIS DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_SH_GIRIS DEFAULT 0,
    CIKIS DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_SH_CIKIS DEFAULT 0,
    BIRIM_MALIYET DECIMAL(19,6) NULL,                                       -- TL, ana birim başına
    CONSTRAINT CK_LM_SH_TEK_YON CHECK (GIRIS >= 0 AND CIKIS >= 0 AND (GIRIS = 0 OR CIKIS = 0))
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_SH_STOK')
    CREATE INDEX IX_LM_SH_STOK ON dbo.LM_STOK_HAREKET (STOK_ID, DEPO_ID, TARIH) INCLUDE (GIRIS, CIKIS);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_SH_BELGE')
    CREATE INDEX IX_LM_SH_BELGE ON dbo.LM_STOK_HAREKET (BELGE_ID);
GO
