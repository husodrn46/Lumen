CREATE OR ALTER TRIGGER dbo.TR_LMV_ORFLINE_EKLE ON dbo.LMV_ORFLINE INSTEAD OF INSERT AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO dbo.LM_BELGE_SATIR (BELGE_ID, SIRA, SATIR_TURU, STOK_ID, BIRIM_ID, CARPAN, MIKTAR, FIYAT, TUTAR, ISKONTO_TUTAR, MASRAF_TUTAR, ISKONTO_ORANI, KDV_ORANI, KDV_TUTAR, KDV_MATRAH, NET, TESLIM_MIKTAR, ACIKLAMA, VADE, DOVIZ_FIYAT, OZEL_KOD, KAPALI, REZERVE_MIKTAR, REZERVE_TARIH, GUID, IPTAL)
    SELECT
        I.ORDFICHEREF,
        ISNULL(I.LINENO_, 0),
        ISNULL(I.LINETYPE, 0),
        NULLIF(I.STOCKREF, 0),
        COALESCE((SELECT TOP 1 SBX.BIRIM_ID FROM dbo.LM_STOK_BIRIM SBX WHERE SBX.ID = I.UOMREF), (SELECT TOP 1 SX.ANA_BIRIM_ID FROM dbo.LM_STOK SX WHERE SX.ID = NULLIF(I.STOCKREF, 0))),
        CASE WHEN I.UINFO1 > 0 AND I.UINFO2 > 0 THEN I.UINFO2 / I.UINFO1 ELSE ISNULL((SELECT TOP 1 SBX.CARPAN FROM dbo.LM_STOK_BIRIM SBX WHERE SBX.ID = I.UOMREF), 1) END,
        ISNULL(I.AMOUNT, 0),
        ISNULL(I.PRICE, 0),
        ISNULL(I.TOTAL, 0),
        ISNULL(I.DISTDISC, 0),
        ISNULL(I.DISTCOST, 0),
        ISNULL(I.DISCPER, 0),
        ISNULL(I.VAT, 0),
        ISNULL(I.VATAMNT, 0),
        ISNULL(I.VATMATRAH, 0),
        ISNULL(I.LINENET, 0),
        ISNULL(I.SHIPPEDAMOUNT, 0),
        I.LINEEXP,
        CAST(I.DUEDATE AS DATE),
        NULLIF(I.PRPRICE, 0),
        I.SPECODE,
        ISNULL(I.CLOSED, 0),
        NULLIF(I.RESERVEAMOUNT, 0),
        CAST(I.RESERVEDATE AS DATE),
        I.GUID,
        ISNULL(I.CANCELLED, 0)
    FROM inserted I
    WHERE EXISTS (SELECT 1 FROM dbo.LM_BELGE BX WHERE BX.ID = I.ORDFICHEREF AND BX.TUR = 1 AND BX.DURUM <> 9);
    IF @@ROWCOUNT > 0
    BEGIN
        DECLARE @yeni INT = CAST(SCOPE_IDENTITY() AS INT);
        EXEC sp_set_session_context N'lumen_yeni_id', @yeni;
    END;
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_ORFLINE_GUNCELLE ON dbo.LMV_ORFLINE INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (SELECT 1 FROM inserted I JOIN dbo.LM_BELGE_SATIR T ON T.ID = I.LOGICALREF
               WHERE ISNULL(I.AMOUNT, 0) < T.TESLIM_MIKTAR - 0.000001)
        THROW 51001, N'Sipariş satırı teslim edilen miktarın altına düşürülemez.', 1;
    UPDATE T SET
