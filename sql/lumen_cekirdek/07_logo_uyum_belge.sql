CREATE OR ALTER TRIGGER dbo.TR_LMV_ORFICHE_EKLE ON dbo.LMV_ORFICHE INSTEAD OF INSERT AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO dbo.LM_BELGE (YON, NO, TARIH, SAAT_KODU, CARI_ID, PERSONEL_ID, DEPO_ID, PARA_BIRIMI, KUR, BRUT, ISKONTO, KDV, NET, DOVIZ_NET, EK_ISKONTO, ACIKLAMA, ACIKLAMA2, ACIKLAMA3, ACIKLAMA4, DOKUMAN_NO, OZEL_KOD, YETKI_KODU, ONAY_DURUMU, YAZDIRMA_SAYISI, GUID, ODEME_PLANI_ID, TUR, DURUM, OLUSTURAN_ID, OLUSTURMA)
    SELECT
        CASE WHEN I.TRCODE = 2 THEN 2 ELSE 1 END,
        ISNULL(I.FICHENO, ''),
        CAST(ISNULL(I.DATE_, SYSDATETIME()) AS DATE),
        I.TIME_,
        NULLIF(I.CLIENTREF, 0),
        NULLIF(I.SALESMANREF, 0),
        (SELECT TOP 1 DX.ID FROM dbo.LM_DEPO DX WHERE DX.NO = ISNULL(I.SOURCEINDEX, 0)),
        CASE ISNULL(I.TRCURR, 0) WHEN 1 THEN 'USD' WHEN 20 THEN 'EUR' WHEN 17 THEN 'GBP' ELSE 'TRY' END,
        CASE WHEN I.TRRATE > 0 THEN I.TRRATE ELSE 1 END,
        ISNULL(I.GROSSTOTAL, 0),
        ISNULL(I.TOTALDISCOUNTS, 0),
        ISNULL(I.TOTALVAT, 0),
        ISNULL(I.NETTOTAL, 0),
        NULLIF(I.TRNET, 0),
        ISNULL(I.ADDDISCOUNTS, 0),
        I.GENEXP1,
        I.GENEXP2,
        I.GENEXP3,
        I.GENEXP4,
        I.DOCODE,
        I.SPECODE,
        I.CYPHCODE,
        ISNULL(I.STATUS, 4),
        ISNULL(I.PRINTCNT, 0),
        I.GUID,
        NULLIF(I.PAYDEFREF, 0),
        1,
        CASE WHEN I.CANCELLED = 1 THEN 9 ELSE 1 END,
        NULLIF(I.CAPIBLOCK_CREATEDBY, 0),
        ISNULL(I.CAPIBLOCK_CREADEDDATE, SYSDATETIME())
    FROM inserted I;
    IF @@ROWCOUNT > 0
    BEGIN
        DECLARE @yeni INT = CAST(SCOPE_IDENTITY() AS INT);
        EXEC sp_set_session_context N'lumen_yeni_id', @yeni;
    END;
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_ORFICHE_GUNCELLE ON dbo.LMV_ORFICHE INSTEAD OF UPDATE AS
BEGIN
    SET NOCOUNT ON;
    UPDATE T SET
        YON = CASE WHEN I.TRCODE = 2 THEN 2 ELSE 1 END,
        NO = ISNULL(I.FICHENO, ''),
        TARIH = CAST(ISNULL(I.DATE_, SYSDATETIME()) AS DATE),
        SAAT_KODU = I.TIME_,
        CARI_ID = NULLIF(I.CLIENTREF, 0),
        PERSONEL_ID = NULLIF(I.SALESMANREF, 0),
        DEPO_ID = (SELECT TOP 1 DX.ID FROM dbo.LM_DEPO DX WHERE DX.NO = ISNULL(I.SOURCEINDEX, 0)),
        PARA_BIRIMI = CASE ISNULL(I.TRCURR, 0) WHEN 1 THEN 'USD' WHEN 20 THEN 'EUR' WHEN 17 THEN 'GBP' ELSE 'TRY' END,
        KUR = CASE WHEN I.TRRATE > 0 THEN I.TRRATE ELSE 1 END,
        BRUT = ISNULL(I.GROSSTOTAL, 0),
        ISKONTO = ISNULL(I.TOTALDISCOUNTS, 0),
        KDV = ISNULL(I.TOTALVAT, 0),
        NET = ISNULL(I.NETTOTAL, 0),
        DOVIZ_NET = NULLIF(I.TRNET, 0),
        EK_ISKONTO = ISNULL(I.ADDDISCOUNTS, 0),
        ACIKLAMA = I.GENEXP1,
        ACIKLAMA2 = I.GENEXP2,
        ACIKLAMA3 = I.GENEXP3,
        ACIKLAMA4 = I.GENEXP4,
        DOKUMAN_NO = I.DOCODE,
        OZEL_KOD = I.SPECODE,
        YETKI_KODU = I.CYPHCODE,
        ONAY_DURUMU = ISNULL(I.STATUS, 4),
        YAZDIRMA_SAYISI = ISNULL(I.PRINTCNT, 0),
        GUID = I.GUID,
        ODEME_PLANI_ID = NULLIF(I.PAYDEFREF, 0),
        DURUM = CASE WHEN I.CANCELLED = 1 THEN 9 WHEN T.DURUM = 9 THEN 1 ELSE T.DURUM END,
        GUNCELLEYEN_ID = NULLIF(I.CAPIBLOCK_MODIFIEDBY, 0),
        GUNCELLEME = SYSDATETIME()
    FROM dbo.LM_BELGE T JOIN inserted I ON I.LOGICALREF = T.ID;
END;
GO

CREATE OR ALTER TRIGGER dbo.TR_LMV_ORFICHE_SIL ON dbo.LMV_ORFICHE INSTEAD OF DELETE AS
BEGIN
    SET NOCOUNT ON;
    DELETE T FROM dbo.LM_BELGE T JOIN deleted X ON X.LOGICALREF = T.ID;
END;
GO

