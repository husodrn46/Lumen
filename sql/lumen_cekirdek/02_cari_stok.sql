IF OBJECT_ID('dbo.LM_CARI', 'U') IS NULL
CREATE TABLE dbo.LM_CARI (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    KOD NVARCHAR(40) NOT NULL,
    UNVAN NVARCHAR(200) NOT NULL,
    TUR TINYINT NOT NULL CONSTRAINT DF_LM_CARI_TUR DEFAULT 3,     -- 1 alıcı, 2 satıcı, 3 alıcı+satıcı
    VERGI_NO NVARCHAR(20) NULL,
    VERGI_DAIRESI NVARCHAR(80) NULL,
    TC_NO NVARCHAR(11) NULL,
    IL NVARCHAR(60) NULL,
    ILCE NVARCHAR(60) NULL,
    ADRES NVARCHAR(400) NULL,
    TELEFON NVARCHAR(40) NULL,
    EPOSTA NVARCHAR(160) NULL,
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_CARI_PB DEFAULT 'TRY' CONSTRAINT FK_LM_CARI_PB REFERENCES dbo.LM_PARA_BIRIMI(KOD),
    VADE_GUN SMALLINT NOT NULL CONSTRAINT DF_LM_CARI_VADE DEFAULT 0,
    RISK_LIMITI DECIMAL(19,4) NULL,
    OZEL_KOD NVARCHAR(40) NULL,
    PAZARLAMACI_ID INT NULL CONSTRAINT FK_LM_CARI_PAZ REFERENCES dbo.LM_PERSONEL(ID),
    AKTIF BIT NOT NULL CONSTRAINT DF_LM_CARI_AKTIF DEFAULT 1,
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_CARI_OLU DEFAULT SYSDATETIME(),
    GUNCELLEME DATETIME2(0) NULL,
    SURUM ROWVERSION,
    CONSTRAINT UQ_LM_CARI_KOD UNIQUE (KOD)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_CARI_UNVAN')
    CREATE INDEX IX_LM_CARI_UNVAN ON dbo.LM_CARI (UNVAN);
GO

IF OBJECT_ID('dbo.LM_DEPO', 'U') IS NULL
CREATE TABLE dbo.LM_DEPO (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    KOD NVARCHAR(20) NOT NULL,
    AD NVARCHAR(80) NOT NULL,
    AKTIF BIT NOT NULL CONSTRAINT DF_LM_DEPO_AKTIF DEFAULT 1,
    CONSTRAINT UQ_LM_DEPO_KOD UNIQUE (KOD)
);
GO

IF OBJECT_ID('FK_LM_PERSONEL_DEPO', 'F') IS NULL
    ALTER TABLE dbo.LM_PERSONEL ADD CONSTRAINT FK_LM_PERSONEL_DEPO FOREIGN KEY (DEPO_ID) REFERENCES dbo.LM_DEPO(ID);
GO

IF OBJECT_ID('dbo.LM_BIRIM', 'U') IS NULL
CREATE TABLE dbo.LM_BIRIM (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    KOD NVARCHAR(20) NOT NULL,                  -- ADET, KOLI, PAKET, KG, M
    AD NVARCHAR(60) NOT NULL,
    CONSTRAINT UQ_LM_BIRIM_KOD UNIQUE (KOD)
);
GO

IF OBJECT_ID('dbo.LM_STOK', 'U') IS NULL
CREATE TABLE dbo.LM_STOK (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    KOD NVARCHAR(40) NOT NULL,
    AD NVARCHAR(200) NOT NULL,
    GRUP NVARCHAR(40) NULL,
    OZEL_KOD NVARCHAR(40) NULL,
    ANA_BIRIM_ID INT NOT NULL CONSTRAINT FK_LM_STOK_BIRIM REFERENCES dbo.LM_BIRIM(ID),
    KDV_ORANI DECIMAL(5,2) NOT NULL CONSTRAINT DF_LM_STOK_KDV DEFAULT 20,
    AGIRLIK_KG DECIMAL(19,6) NULL,
    HACIM_M3 DECIMAL(19,6) NULL,
    STOK_TAKIPLI BIT NOT NULL CONSTRAINT DF_LM_STOK_TAKIP DEFAULT 1,   -- hizmet kartı = 0
    AKTIF BIT NOT NULL CONSTRAINT DF_LM_STOK_AKTIF DEFAULT 1,
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_STOK_OLU DEFAULT SYSDATETIME(),
    GUNCELLEME DATETIME2(0) NULL,
    SURUM ROWVERSION,
    CONSTRAINT UQ_LM_STOK_KOD UNIQUE (KOD)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_STOK_AD')
    CREATE INDEX IX_LM_STOK_AD ON dbo.LM_STOK (AD);
GO

-- Stokun kullanılabilir birimleri ve ana birime çevrim (1 KOLI = 24 ADET → CARPAN 24).
IF OBJECT_ID('dbo.LM_STOK_BIRIM', 'U') IS NULL
CREATE TABLE dbo.LM_STOK_BIRIM (
    STOK_ID INT NOT NULL CONSTRAINT FK_LM_SB_STOK REFERENCES dbo.LM_STOK(ID),
    BIRIM_ID INT NOT NULL CONSTRAINT FK_LM_SB_BIRIM REFERENCES dbo.LM_BIRIM(ID),
    CARPAN DECIMAL(19,6) NOT NULL CONSTRAINT CK_LM_SB_CARPAN CHECK (CARPAN > 0),
    CONSTRAINT PK_LM_STOK_BIRIM PRIMARY KEY (STOK_ID, BIRIM_ID)
);
GO

IF OBJECT_ID('dbo.LM_BARKOD', 'U') IS NULL
CREATE TABLE dbo.LM_BARKOD (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    STOK_ID INT NOT NULL CONSTRAINT FK_LM_BARKOD_STOK REFERENCES dbo.LM_STOK(ID),
    BIRIM_ID INT NOT NULL CONSTRAINT FK_LM_BARKOD_BIRIM REFERENCES dbo.LM_BIRIM(ID),
    BARKOD NVARCHAR(60) NOT NULL,
    CONSTRAINT UQ_LM_BARKOD UNIQUE (BARKOD)
);
GO

-- Fiyatlar: TUR 1 = satış, 2 = alış. Geçerli fiyat = BASLANGIC'ı bugüne en yakın olan.
IF OBJECT_ID('dbo.LM_FIYAT', 'U') IS NULL
CREATE TABLE dbo.LM_FIYAT (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    STOK_ID INT NOT NULL CONSTRAINT FK_LM_FIYAT_STOK REFERENCES dbo.LM_STOK(ID),
    TUR TINYINT NOT NULL,
    BIRIM_ID INT NOT NULL CONSTRAINT FK_LM_FIYAT_BIRIM REFERENCES dbo.LM_BIRIM(ID),
    FIYAT DECIMAL(19,4) NOT NULL,
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_FIYAT_PB DEFAULT 'TRY' CONSTRAINT FK_LM_FIYAT_PB REFERENCES dbo.LM_PARA_BIRIMI(KOD),
    KDV_DAHIL BIT NOT NULL CONSTRAINT DF_LM_FIYAT_KDVD DEFAULT 0,
    BASLANGIC DATE NOT NULL CONSTRAINT DF_LM_FIYAT_BAS DEFAULT CAST(SYSDATETIME() AS DATE),
    CONSTRAINT CK_LM_FIYAT_TUR CHECK (TUR IN (1, 2))
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_FIYAT_STOK')
    CREATE INDEX IX_LM_FIYAT_STOK ON dbo.LM_FIYAT (STOK_ID, TUR, BASLANGIC DESC);
GO

