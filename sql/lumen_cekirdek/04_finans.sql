-- ============================================================================
-- Lumen çekirdek şeması — 04: cari hareket, kasa/banka, çek/senet
-- LOGO karşılıkları: CLFLINE (cari hareket), KSCARD/KSLINES (kasa), BANKACC/BNFLINE
-- (banka), CSCARD/CSROLL/CSTRANS (çek/senet portföy, bordro, hareket).
-- ============================================================================

-- Kasa ve banka hesapları tek tabloda (TUR 1 kasa, 2 banka).
IF OBJECT_ID('dbo.LM_FINANS_HESAP', 'U') IS NULL
CREATE TABLE dbo.LM_FINANS_HESAP (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TUR TINYINT NOT NULL,
    KOD NVARCHAR(30) NOT NULL,
    AD NVARCHAR(120) NOT NULL,
    BANKA_ADI NVARCHAR(80) NULL,
    IBAN NVARCHAR(34) NULL,
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_FH_PB DEFAULT 'TRY' CONSTRAINT FK_LM_FH_PB REFERENCES dbo.LM_PARA_BIRIMI(KOD),
    AKTIF BIT NOT NULL CONSTRAINT DF_LM_FH_AKTIF DEFAULT 1,
    CONSTRAINT UQ_LM_FH_KOD UNIQUE (KOD),
    CONSTRAINT CK_LM_FH_TUR CHECK (TUR IN (1, 2))
);
GO

-- Tahsilat / ödeme / virman / masraf fişleri (kasa veya banka tarafı).
-- TUR: 1 tahsilat, 2 ödeme, 3 virman, 4 masraf, 5 açılış
IF OBJECT_ID('dbo.LM_FINANS_FIS', 'U') IS NULL
CREATE TABLE dbo.LM_FINANS_FIS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TUR TINYINT NOT NULL,
    NO NVARCHAR(30) NOT NULL,
    TARIH DATE NOT NULL,
    HESAP_ID INT NOT NULL CONSTRAINT FK_LM_FF_HESAP REFERENCES dbo.LM_FINANS_HESAP(ID),
    KARSI_HESAP_ID INT NULL CONSTRAINT FK_LM_FF_KARSI REFERENCES dbo.LM_FINANS_HESAP(ID),   -- virmanda
    CARI_ID INT NULL CONSTRAINT FK_LM_FF_CARI REFERENCES dbo.LM_CARI(ID),
    TUTAR DECIMAL(19,4) NOT NULL CONSTRAINT CK_LM_FF_TUTAR CHECK (TUTAR > 0),
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_FF_PB DEFAULT 'TRY',
    KUR DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_FF_KUR DEFAULT 1,
    ACIKLAMA NVARCHAR(400) NULL,
    DURUM TINYINT NOT NULL CONSTRAINT DF_LM_FF_DURUM DEFAULT 1,              -- 1 geçerli, 9 iptal
    ISTEK_ID VARCHAR(40) NULL,                                              -- mükerrer gönderim koruması
    OLUSTURAN_ID INT NULL,
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_FF_OLU DEFAULT SYSDATETIME(),
    CONSTRAINT UQ_LM_FF_NO UNIQUE (TUR, NO),
    CONSTRAINT CK_LM_FF_TUR CHECK (TUR BETWEEN 1 AND 5)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_LM_FF_ISTEK')
    CREATE UNIQUE INDEX UQ_LM_FF_ISTEK ON dbo.LM_FINANS_FIS (ISTEK_ID) WHERE ISTEK_ID IS NOT NULL;
GO

-- Kasa/banka hareketi (bakiye = SUM(GIRIS) - SUM(CIKIS), hesabın para biriminde).
IF OBJECT_ID('dbo.LM_FINANS_HAREKET', 'U') IS NULL
CREATE TABLE dbo.LM_FINANS_HAREKET (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    HESAP_ID INT NOT NULL CONSTRAINT FK_LM_FHR_HESAP REFERENCES dbo.LM_FINANS_HESAP(ID),
    TARIH DATE NOT NULL,
    FIS_ID INT NOT NULL CONSTRAINT FK_LM_FHR_FIS REFERENCES dbo.LM_FINANS_FIS(ID),
    GIRIS DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_FHR_G DEFAULT 0,
    CIKIS DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_FHR_C DEFAULT 0,
    ACIKLAMA NVARCHAR(400) NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_FHR_HESAP')
    CREATE INDEX IX_LM_FHR_HESAP ON dbo.LM_FINANS_HAREKET (HESAP_ID, TARIH) INCLUDE (GIRIS, CIKIS);
GO

-- Çek / senet kartı. TUR: 1 müşteri çeki, 2 kendi çekimiz, 3 müşteri senedi, 4 kendi senedimiz
-- DURUM: 1 portföyde, 2 ciro edildi, 3 tahsil edildi, 4 bankaya verildi, 5 karşılıksız, 6 iade, 7 ödendi (kendi)
IF OBJECT_ID('dbo.LM_CEK', 'U') IS NULL
CREATE TABLE dbo.LM_CEK (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TUR TINYINT NOT NULL,
    PORTFOY_NO NVARCHAR(30) NOT NULL,
    SERI_NO NVARCHAR(40) NULL,
    BANKA NVARCHAR(80) NULL,
    SUBE NVARCHAR(80) NULL,
    BORCLU NVARCHAR(200) NULL,
    VADE DATE NOT NULL,
    TUTAR DECIMAL(19,4) NOT NULL CONSTRAINT CK_LM_CEK_TUTAR CHECK (TUTAR > 0),
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_CEK_PB DEFAULT 'TRY',
    DURUM TINYINT NOT NULL CONSTRAINT DF_LM_CEK_DURUM DEFAULT 1,
    ALINAN_CARI_ID INT NULL CONSTRAINT FK_LM_CEK_ALINAN REFERENCES dbo.LM_CARI(ID),
    VERILEN_CARI_ID INT NULL CONSTRAINT FK_LM_CEK_VERILEN REFERENCES dbo.LM_CARI(ID),
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_CEK_OLU DEFAULT SYSDATETIME(),
    SURUM ROWVERSION,
    CONSTRAINT UQ_LM_CEK_PORTFOY UNIQUE (PORTFOY_NO),
    CONSTRAINT CK_LM_CEK_TUR CHECK (TUR BETWEEN 1 AND 4)
);
GO

-- Çek hareketi (bordro satırı): giriş, ciro, tahsil, iade ... Geri alma = ters hareket.
IF OBJECT_ID('dbo.LM_CEK_HAREKET', 'U') IS NULL
CREATE TABLE dbo.LM_CEK_HAREKET (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CEK_ID INT NOT NULL CONSTRAINT FK_LM_CH_CEK REFERENCES dbo.LM_CEK(ID),
    TARIH DATE NOT NULL,
    BORDRO_NO NVARCHAR(30) NOT NULL,
    ISLEM TINYINT NOT NULL,                        -- DURUM ile aynı kodlar (yeni durum)
    ONCEKI_DURUM TINYINT NULL,
    CARI_ID INT NULL CONSTRAINT FK_LM_CH_CARI REFERENCES dbo.LM_CARI(ID),
    HESAP_ID INT NULL CONSTRAINT FK_LM_CH_HESAP REFERENCES dbo.LM_FINANS_HESAP(ID),
    ACIKLAMA NVARCHAR(400) NULL,
    GERI_ALINDI BIT NOT NULL CONSTRAINT DF_LM_CH_GERI DEFAULT 0,
    ISTEK_ID VARCHAR(40) NULL,
    OLUSTURAN_ID INT NULL,
    OLUSTURMA DATETIME2(0) NOT NULL CONSTRAINT DF_LM_CH_OLU DEFAULT SYSDATETIME()
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_LM_CH_ISTEK')
    CREATE UNIQUE INDEX UQ_LM_CH_ISTEK ON dbo.LM_CEK_HAREKET (ISTEK_ID) WHERE ISTEK_ID IS NOT NULL;
GO

-- Cari hareket: borç/alacak TL; dövizli işlemde döviz tutarı ayrıca. Bakiye = SUM(BORC - ALACAK).
-- KAYNAK: 1 belge (fatura), 2 finans fişi, 3 çek hareketi, 4 açılış/virman
IF OBJECT_ID('dbo.LM_CARI_HAREKET', 'U') IS NULL
CREATE TABLE dbo.LM_CARI_HAREKET (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CARI_ID INT NOT NULL CONSTRAINT FK_LM_CRH_CARI REFERENCES dbo.LM_CARI(ID),
    TARIH DATE NOT NULL,
    VADE DATE NULL,
    KAYNAK TINYINT NOT NULL,
    BELGE_ID INT NULL CONSTRAINT FK_LM_CRH_BELGE REFERENCES dbo.LM_BELGE(ID),
    FINANS_FIS_ID INT NULL CONSTRAINT FK_LM_CRH_FF REFERENCES dbo.LM_FINANS_FIS(ID),
    CEK_HAREKET_ID INT NULL CONSTRAINT FK_LM_CRH_CH REFERENCES dbo.LM_CEK_HAREKET(ID),
    BELGE_NO NVARCHAR(30) NULL,
    BORC DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_CRH_B DEFAULT 0,
    ALACAK DECIMAL(19,4) NOT NULL CONSTRAINT DF_LM_CRH_A DEFAULT 0,
    PARA_BIRIMI CHAR(3) NOT NULL CONSTRAINT DF_LM_CRH_PB DEFAULT 'TRY',
    KUR DECIMAL(19,6) NOT NULL CONSTRAINT DF_LM_CRH_KUR DEFAULT 1,
    DOVIZ_TUTAR DECIMAL(19,4) NULL,
    ACIKLAMA NVARCHAR(400) NULL,
    CONSTRAINT CK_LM_CRH_TEK_YON CHECK (BORC >= 0 AND ALACAK >= 0 AND (BORC = 0 OR ALACAK = 0))
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LM_CRH_CARI')
    CREATE INDEX IX_LM_CRH_CARI ON dbo.LM_CARI_HAREKET (CARI_ID, TARIH) INCLUDE (BORC, ALACAK);
GO

